@dataclass(frozen=True)
class Palette:
    name: str
    # page and surfaces
    bg: str
    surface: str
    surface_2: str  # inputs, hovered rows
    border: str  # decoration between blocks
    border_strong: str  # edges of controls: 3:1 against the surface
    text: str
    muted: str
    # primary: the main action
    primary: str  # fill
    on_primary: str  # label on the fill
    primary_text: str  # links, small accents on the page
    # secondary: the second action, markers, soil and geography
    secondary: str
    on_secondary: str
    secondary_text: str
    # highlight: attention that is not an error
    highlight: str
    on_highlight: str
    highlight_text: str
    # tinted backgrounds of the good / caution / problem banners
    good_bg: str
    caution_bg: str
    problem_bg: str
    # maps and charts
    outline: str  # the survey area
    points: str  # photo positions
    marker: str  # the takeoff point
    ramp: tuple[str, str, str]  # little to plenty of overlap
    missions: tuple[str, ...]


