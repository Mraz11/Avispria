# runs before the page is painted, so a dark phone never flashes light; same file on the phone page
THEME_BOOT_JS = """(function () {
  var stored = null;
  try { stored = localStorage.getItem("avispria.theme"); } catch (e) {}
  var dark = stored ? stored === "dark"
    : !!(window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches);
  document.documentElement.setAttribute("data-theme", dark ? "dark" : "light");
})();
"""


def _variables(p: Palette, *, quasar: bool) -> str:
    lines = [
        f"  --{f.name.replace('_', '-')}: {getattr(p, f.name)};"
        for f in fields(p)
        if isinstance(getattr(p, f.name), str) and f.name != "name"
    ]
    if quasar:  # Quasar (the toolkit under NiceGUI) reads its own variable names
        lines += [
            f"  --q-primary: {p.primary};",
            f"  --q-secondary: {p.secondary};",
            f"  --q-accent: {p.highlight};",
            f"  --q-positive: {p.primary};",
            f"  --q-negative: {p.secondary};",
            f"  --q-warning: {p.highlight};",
            f"  --q-info: {p.outline if p.name == 'dark' else p.primary_text};",
            f"  --q-dark: {p.surface};",
            f"  --q-dark-page: {p.bg};",
        ]
    lines.append(f"  color-scheme: {p.name};")
    return "\n".join(lines)


def tokens_css(*, quasar: bool = False) -> str:
    """CSS variables for both modes.

    Dark applies when the page says so (``data-theme="dark"``, set before painting from the saved
    choice or the phone's setting), when Quasar is in dark mode, and, without JavaScript, when the
    system prefers dark.
    """
    light, dark = _variables(LIGHT, quasar=quasar), _variables(DARK, quasar=quasar)
    return (
        f":root {{\n{light}\n}}\n"
        f':root[data-theme="dark"],\nbody.body--dark {{\n{dark}\n}}\n'
        f"@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme]) {{\n"
        + "\n".join("  " + line for line in dark.splitlines())
        + "\n  }\n}\n"
    )
