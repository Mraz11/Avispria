"""Generate and check the files of the phone field page that come from the Python code.

* ``field-page/js/generated.js``: camera data copied from ``drones.toml`` (one source of truth)
* ``tests/field_page/golden.json``: expected values computed by the real planner, which the
  page's JavaScript calculators are tested against
* ``field-page/sw.js``: the list of files to keep offline and a build id, so a phone always
  picks up a new version

Run ``python scripts/field_page.py`` after changing the page or the camera data, and
``python scripts/field_page.py --check`` to see whether everything is current.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "field-page"
GENERATED_JS = SITE / "js" / "generated.js"
GOLDEN = ROOT / "tests" / "field_page" / "golden.json"
SERVICE_WORKER = SITE / "sw.js"
NOT_SHIPPED = {"package.json"}  # for Node's module loader only; the page never fetches it
BEGIN, END = "// BEGIN GENERATED ASSETS", "// END GENERATED ASSETS"

sys.path.insert(0, str(ROOT / "src"))


def _num(value: float) -> float:
    return float(f"{value:.12g}")  # stable text, no float noise


def cameras_js() -> str:
    from avispria.adapters.profiles import load_profiles
    from avispria.core.version import __version__

    cameras = {}
    for key, p in sorted(load_profiles().items()):
        cameras[key] = {
            "name": p.name,
            "verified": p.verified,
            "maxSpeed": _num(p.max_speed_ms),
            "modes": {
                mode: {
                    "sensorW": _num(c.sensor_width_mm),
                    "sensorH": _num(c.sensor_height_mm),
                    "focal": _num(c.focal_mm),
                    "w": c.image_width_px,
                    "h": c.image_height_px,
                    "minInterval": _num(c.min_interval_s),
                    "readout": _num(c.readout_s),
                }
                for mode, c in sorted(p.modes.items())
            },
        }
    return (
        "// SPDX-FileCopyrightText: 2026 Avispria contributors\n"
        "// SPDX-License-Identifier: AGPL-3.0-or-later\n"
        "// GENERATED by scripts/field_page.py from src/avispria/data/drones.toml. Do not edit.\n"
        f"export const AVISPRIA_VERSION = {json.dumps(__version__)};\n"
        f"export const CAMERAS = {json.dumps(cameras, indent=2)};\n"
    )


# ---------------------------------------------------------------- golden values
def golden() -> dict:  # type: ignore[type-arg]
    from avispria.adapters.profiles import load_profiles
    from avispria.core.camera import altitude_for_gsd, footprint_m, gsd_m, spacing_m
    from avispria.core.geometry import rectangle_polygon
    from avispria.core.mission import PhotoMode
    from avispria.core.planner import PlanRequest, plan
    from avispria.core.predict import planned_photos
    from avispria.core.safety import SafetyLimits
    from avispria.core.speed import solve_speed

    profiles = load_profiles()
    camera_cases, height_cases, speed_cases, survey_cases, canopy_cases = [], [], [], [], []
    for key, p in sorted(profiles.items()):
        for mode, cam in sorted(p.modes.items()):
            for h in (30.0, 60.0, 100.0):
                across, along = footprint_m(cam, h)
                sp = spacing_m(cam, h, 0.8, 0.7)
                camera_cases.append(
                    {
                        "camera": key,
                        "mode": mode,
                        "height": h,
                        "gsd_m": gsd_m(cam, h),
                        "across": across,
                        "along": along,
                        "photo_m": sp.photo_m,
                        "line_m": sp.line_m,
                    }
                )
            for gsd_cm in (1.0, 2.0, 3.0):
                height_cases.append(
                    {
                        "camera": key,
                        "mode": mode,
                        "gsd_cm": gsd_cm,
                        "height": altitude_for_gsd(cam, gsd_cm / 100.0),
                    }
                )
    lito = profiles["lito-x1"]
    for mode, cam in sorted(lito.modes.items()):
        for h in (40.0, 80.0):
            for front in (0.8, 0.7):
                for shutter in (1 / 1000, 1 / 2000):
                    for wind in (0.0, 5.0, 7.0):
                        photo_m = spacing_m(cam, h, front, 0.7).photo_m
                        s = solve_speed(
                            cam, gsd_m(cam, h), shutter, photo_m, lito.max_speed_ms, wind_ms=wind
                        )
                        speed_cases.append(
                            {
                                "camera": "lito-x1",
                                "mode": mode,
                                "height": h,
                                "front": front,
                                "shutter": shutter,
                                "wind": wind,
                                "photo_m": photo_m,
                                "speed": s.speed_ms,
                                "binding": s.binding,
                                "feasible": s.feasible,
                                "limits": {
                                    "blur": s.blur_ms,
                                    "skew": s.skew_ms,
                                    "trigger": s.trigger_ms,
                                    "wind": s.wind_ms,
                                    "drone": s.drone_ms,
                                },
                            }
                        )
    for width, length, height, front, side, battery in (
        (80.0, 120.0, 40.0, 0.8, 0.7, 20.0),
        (150.0, 300.0, 60.0, 0.8, 0.7, 20.0),
        (200.0, 200.0, 50.0, 0.75, 0.65, 20.0),
        (400.0, 600.0, 80.0, 0.8, 0.7, 20.0),
        (300.0, 500.0, 100.0, 0.8, 0.7, 15.0),
    ):
        cam = lito.modes["12mp"]
        aoi = rectangle_polygon(23.8103, 90.4125, width, length, 0.0)
        res = plan(
            PlanRequest(
                aoi=aoi,
                camera=cam,
                drone_max_speed_ms=lito.max_speed_ms,
                takeoff_lon=aoi.centroid.x,
                takeoff_lat=aoi.centroid.y,
                agl_m=height,
                front_overlap=front,
                side_overlap=side,
                photo_mode=PhotoMode.INTERVAL,
                flat_terrain=True,
                shutter_s=1 / 1000,
                wind_ms=0.0,
                limits=SafetyLimits(max_flight_time_s=battery * 60.0),
                name="golden",
            )
        )
        s = res.summary
        survey_cases.append(
            {
                "camera": "lito-x1",
                "mode": "12mp",
                "width": width,
                "length": length,
                "height": height,
                "front": front,
                "side": side,
                "shutter": 1 / 1000,
                "wind": 0.0,
                "battery_min": battery,
                "strips": s.strips,
                "photo_m": s.photo_spacing_m,
                "line_m": s.line_spacing_m,
                "speed": s.speed.speed_ms,
                "binding": s.speed.binding,
                "interval_s": s.photo_interval_s,
                "missions": [
                    {"minutes": m.estimated_duration_s / 60.0, "photos": len(planned_photos(m))}
                    for m in res.missions
                ],
                "total_minutes": sum(m.estimated_duration_s for m in res.missions) / 60.0,
                "total_photos": sum(len(planned_photos(m)) for m in res.missions),
            }
        )
    cam = lito.modes["12mp"]
    for flight, canopy in ((60.0, 0.0), (60.0, 15.0), (80.0, 25.0), (100.0, 30.0)):
        planned = spacing_m(cam, flight, 0.8, 0.7)
        across, along = footprint_m(cam, flight - canopy)
        canopy_cases.append(
            {
                "camera": "lito-x1",
                "mode": "12mp",
                "flight": flight,
                "canopy": canopy,
                "front": 0.8,
                "side": 0.7,
                "above": flight - canopy,
                "gsd_canopy_m": gsd_m(cam, flight - canopy),
                "gsd_ground_m": gsd_m(cam, flight),
                "front_actual": 1 - planned.photo_m / along,
                "side_actual": 1 - planned.line_m / across,
            }
        )
    return {
        "camera": camera_cases,
        "height": height_cases,
        "speed": speed_cases,
        "survey": survey_cases,
        "canopy": canopy_cases,
    }


def golden_text() -> str:
    def clean(v):  # type: ignore[no-untyped-def]
        if isinstance(v, float):
            return float(f"{v:.12g}") if math.isfinite(v) else v
        if isinstance(v, dict):
            return {k: clean(x) for k, x in v.items()}
        if isinstance(v, list):
            return [clean(x) for x in v]
        return v

    return json.dumps(clean(golden()), indent=1, sort_keys=True) + "\n"


# --------------------------------------------------------------- offline cache
def shipped_files(extra: dict[str, str] | None = None) -> list[str]:
    """Every file the phone needs offline (relative paths, forward slashes), sw.js excluded.

    ``extra`` names files that will exist once generated (path -> content), so a check can
    be made without writing anything.
    """
    names = set(extra or {})
    for path in SITE.rglob("*"):
        rel = path.relative_to(SITE).as_posix()
        if (
            path.is_file()
            and rel not in NOT_SHIPPED
            and rel != "sw.js"
            and not path.name.startswith(".")
        ):
            names.add(rel)
    return sorted(names)


def build_id(extra: dict[str, str] | None = None) -> str:
    digest = hashlib.sha256()
    for rel in shipped_files(extra):
        data = extra[rel].encode() if extra and rel in extra else (SITE / rel).read_bytes()
        digest.update(rel.encode() + b"\0" + data + b"\0")
    return digest.hexdigest()[:12]


def stamped_service_worker(text: str, extra: dict[str, str] | None = None) -> str:
    assets = ["./", *shipped_files(extra)]
    block = BEGIN + "\nconst ASSETS = " + json.dumps(assets, indent=2) + ";\n" + END
    text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _m: block, text, flags=re.S)
    return re.sub(r'const BUILD = "[0-9a-f]{12}";', f'const BUILD = "{build_id(extra)}";', text)


def expected_files() -> dict[Path, str]:
    """The generated files with the content they should have right now (nothing is written)."""
    generated = {"js/generated.js": cameras_js()}  # shipped, so part of the offline list and id
    return {
        GENERATED_JS: generated["js/generated.js"],
        GOLDEN: golden_text(),
        SERVICE_WORKER: stamped_service_worker(
            SERVICE_WORKER.read_text(encoding="utf-8"), generated
        ),
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale = []
    for path, text in expected_files().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check:
        print("out of date: " + ", ".join(stale) if stale else "all generated files are current")
        return 1 if stale else 0
    print("updated: " + ", ".join(stale) if stale else "nothing to update")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
